WORKSPACE = "step5_test"


@pytest.fixture
def con():
    """
    A workspace-scoped connection, not a bare duckdb.connect().

    Every loader calls db.register_dataset on success, and that writes to
    _agent_datasets -- a table only db.connect() creates. A bare connection
    loads the data correctly and then falls over on the very next line, which
    is exactly what happened the first time these tests met the real db module.

    Its own workspace, like tests/test_phase2.py uses phase2_test, so nothing
    loaded in 'local' is touched.
    """
    workspace.reset(WORKSPACE)
    c = db.connect(WORKSPACE)
    try:
        yield c
    finally:
        c.close()
        workspace.reset(WORKSPACE)


