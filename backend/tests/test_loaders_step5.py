def test_csv_footer_rows_are_dropped(con, dirty_csv):
    r = load_csv(con, dirty_csv, "d", on_error="null", footer_skip_rows=1)
    assert r.row_count == 22
    assert con.execute("SELECT count(*) FROM d WHERE id='TOTAL'").fetchone()[0] == 0


def test_csv_footer_skip_keeps_the_first_rows_not_arbitrary_ones(con, tmp_path):
    """
    read_csv has no skipfooter, so this is done with count(*) then LIMIT. That
    is only correct because a scan preserves file order -- checked here at
    threads=8, where a parallel scan would show up.
    """
    con.execute("SET threads=8")
    p = tmp_path / "ord.csv"
    p.write_text("id\n" + "".join(f"{i}\n" for i in range(1, 5001)) + "TOTAL\n")

    load_csv(con, str(p), "o", footer_skip_rows=1, dtypes={"id": "VARCHAR"})
    kept = [r[0] for r in con.execute("SELECT id FROM o").fetchall()]
    assert kept == [str(i) for i in range(1, 5001)]


