def test_on_error_defaults_to_stop():
    import inspect

    for fn in (load_csv, load_excel):
        assert inspect.signature(fn).parameters["on_error"].default == "stop"


def test_an_unknown_on_error_mode_is_refused():
    with pytest.raises(LoadRefused) as exc:
        validate_on_error("skip")
    assert "NEXT STEP" in str(exc.value)


def test_csv_stop_refuses_a_value_that_will_not_convert(con, dirty_csv):
    with pytest.raises(LoadRefused) as exc:
        load_csv(con, dirty_csv, "d", dtypes={"units": "BIGINT"}, footer_skip_rows=1)
    assert "NEXT STEP" in str(exc.value)


def test_csv_null_counts_per_column_and_keeps_the_rows(con, dirty_csv):
    r = load_csv(
        con,
        dirty_csv,
        "d",
        on_error="null",
        footer_skip_rows=1,
        dtypes={"units": "BIGINT", "price": "DOUBLE"},
    )
    assert r.coercion_failures == {"units": 1}
    assert r.row_count == 22
    assert con.execute('SELECT units FROM d WHERE id=22').fetchone()[0] is None


def test_na_values_are_not_counted_as_coercion_failures(con, dirty_csv):
    """'N/A' is a declared null, not a value that failed to convert."""
    r = load_csv(
        con, dirty_csv, "d", on_error="null", footer_skip_rows=1,
        na_values=["N/A"], dtypes={"units": "BIGINT"},
    )
    assert r.coercion_failures.get("units", 0) == 1  # 'oops' only
    assert con.execute('SELECT units FROM d WHERE id=21').fetchone()[0] is None


