"""
Tests for the Phase 3 Step 5 loader changes.

These run against a real DuckDB connection and real files, because every one of
them is about behaviour that only shows up when the data actually moves:
whether a footer row reaches the type sniffer, whether a bad cell nulls or
stops, whether the spec's row numbers survive the trip.

The last group drives a load entirely from an IngestSpec. That is the first
point in Phase 3 where a spec produces a table.
"""

