def test_excel_na_values_are_applied_before_type_inference(con, tmp_path):
    """
    Without this, a column of integers containing 'N/A' is VARCHAR -- F5. The
    token has to become None before the sniffer sees the column.
    """
    wb = Workbook()
    ws = wb.active
    ws.title = "S"
    ws.append(["id", "units"])
    ws.append([1, 10])
    ws.append([2, "N/A"])
    ws.append([3, 30])
    p = tmp_path / "na.xlsx"
    wb.save(p)

    plain = load_excel(con, str(p), "p", sheet="S")
    assert dict(plain.columns)["units"] == "VARCHAR"

    with_na = load_excel(con, str(p), "q", sheet="S", na_values=["N/A"])
    assert dict(with_na.columns)["units"] == "BIGINT"
    assert con.execute("SELECT units FROM q WHERE id=2").fetchone()[0] is None


def test_excel_na_values_only_match_strings(con, tmp_path):
    """A numeric 0 is not a null token however the token list is written."""
    wb = Workbook()
    ws = wb.active
    ws.title = "S"
    ws.append(["id", "units"])
    ws.append([1, 0])
    ws.append([2, 5])
    p = tmp_path / "zero.xlsx"
    wb.save(p)

    r = load_excel(con, str(p), "z", sheet="S", na_values=["0"])
    assert con.execute("SELECT units FROM z WHERE id=1").fetchone()[0] == 0
    assert r.coercion_failures == {}


