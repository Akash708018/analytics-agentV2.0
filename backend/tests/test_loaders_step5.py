def test_a_spec_loads_the_messy_workbook_without_eating_the_title(con, messy_xlsx):
    """
    Header at row 5, data from row 6. The spec says header_rows=[5]; the loader
    must be told 5, not 1. Getting that wrong loads the title as data and types
    every column VARCHAR -- F12 producing F5.
    """
    spec = IngestSpec(
        path=messy_xlsx,
        source_type="excel",
        dataset_name="messy",
        sheet="Report",
        header_rows=[5],
        data_start_row=6,
        footer_skip_rows=1,
        columns=[
            ColumnSpec(source_name="order_id", target_name="order_id"),
            ColumnSpec(source_name="units", target_name="units"),
            ColumnSpec(source_name="when", target_name="when"),
        ],
    )
    assert len(spec.header_rows) == 1
    assert spec.loader_header_rows == 5

    result = load_excel(con, messy_xlsx, **spec.to_loader_kwargs(load_excel))

    assert result.row_count == 10
    assert dict(result.columns)["units"] == "BIGINT"
    first = con.execute(
        "SELECT order_id FROM messy ORDER BY units LIMIT 1"
    ).fetchone()[0]
    assert first == "A1"
    assert con.execute(
        "SELECT count(*) FROM messy WHERE order_id LIKE 'Quarterly%'"
    ).fetchone()[0] == 0


def test_the_spec_bridge_no_longer_refuses_na_values_or_footer_skip():
    """
    Step 3 left to_loader_kwargs raising SpecNotSupported for both fields.
    Adding them to the loaders is what makes that stop -- and this is the test
    that says the to-do list is done.
    """
    spec = IngestSpec(
        path="x.xlsx",
        source_type="excel",
        dataset_name="x",
        sheet="S",
        header_rows=[1],
        data_start_row=2,
        na_values=["N/A"],
        footer_skip_rows=2,
        columns=[ColumnSpec(source_name="Units", target_name="units")],
    )
    kwargs = spec.to_loader_kwargs(load_excel)
    assert kwargs["na_values"] == ["N/A"]
    assert kwargs["footer_skip_rows"] == 2

    csv_spec = IngestSpec(
        path="x.csv",
        source_type="csv",
        dataset_name="x",
        header_rows=[1],
        data_start_row=2,
        na_values=["-"],
        footer_skip_rows=1,
        columns=[ColumnSpec(source_name="Units", target_name="units")],
    )
    kwargs = csv_spec.to_loader_kwargs(load_csv)
    assert kwargs["footer_skip_rows"] == 1


