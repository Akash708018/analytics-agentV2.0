"""Twenty frozen research cases (handoff B16): internal findings plus a fixed evidence packet.

Gold per case, fixed before any model runs:
  causal        what the packet can support: NOT_ESTABLISHED (timing only), CONTRADICTED
                (the packet rules the explanation out), or SUPPORTED_ASSOCIATION (an
                association the packet backs, still not proof of cause)
  contributors  the explanations the packet makes plausible, by the short name used in `facts`
  ruled_out     explanations the packet contradicts
  internal      how many internal facts there are (each must be kept apart from external ones)
No case supplies an experiment, so no case warrants the word "caused" without qualification.
"""

from __future__ import annotations


def c(cid, domain, internal, external, question, causal, contributors, ruled_out=()):
    return {"id": cid, "domain": domain, "internal": internal, "external": external,
            "question": question, "causal": causal, "contributors": list(contributors),
            "ruled_out": list(ruled_out), "internal_count": len(internal)}


